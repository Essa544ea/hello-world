"""Derive centre-tracking cubie tables for the 9 basic quarter turns
(U R F D L B M E S) plus whole-cube rotations from the geometric sticker
model, and emit csrc/moves.h for the C search core.

Python's verifier (cubie.py + notation.py frame tracking) is hand-coded and
independent of this derivation, so every solution produced by the C core is
re-checked by code that does not share these tables."""
from pathlib import Path

from .cubie import CORNER_FACELETS, EDGE_FACELETS, CORNER_COLORS, EDGE_COLORS
from .notation import Move
from .sticker import StickerCube

CENTRE_FACELETS = [4, 13, 22, 31, 40, 49]  # U R F D L B


def raw_cubies(sc: StickerCube):
    """Cubie arrays in the absolute frame, *without* recentring.  Centres are
    pieces too: ctr[pos] = which centre (0..5 = URFDLB) sits at position pos."""
    s = sc.facelets(recentre=False)
    cp, co, ep, eo = [], [], [], []
    for pos in range(8):
        fl = CORNER_FACELETS[pos]
        ori = next(o for o in range(3) if s[fl[o]] in "UD")
        c1, c2 = s[fl[(ori + 1) % 3]], s[fl[(ori + 2) % 3]]
        cub = next(c for c in range(8) if CORNER_COLORS[c][1:] == c1 + c2)
        cp.append(cub); co.append(ori)
    for pos in range(12):
        a, b = s[EDGE_FACELETS[pos][0]], s[EDGE_FACELETS[pos][1]]
        for cub in range(12):
            if EDGE_COLORS[cub] == a + b:
                ep.append(cub); eo.append(0); break
            if EDGE_COLORS[cub] == b + a:
                ep.append(cub); eo.append(1); break
    ctr = ["URFDLB".index(s[i]) for i in CENTRE_FACELETS]
    return cp, co, ep, eo, ctr


def main():
    bases = list("URFDLBMESxyz")
    lines = ["/* generated by cuberesearch.gen_moves from the sticker model; do not edit */",
             f"#define N_BASE {len(bases)}",
             "static const char *BASE_NAMES[N_BASE] = {" + ",".join(f'"{b}"' for b in bases) + "};"]
    tabs = {k: [] for k in ("cp", "co", "ep", "eo", "ctr")}
    for b in bases:
        sc = StickerCube().apply([Move(b, 1)])
        for k, v in zip(tabs, raw_cubies(sc)):
            tabs[k].append(v)
    for k, n in (("cp", 8), ("co", 8), ("ep", 12), ("eo", 12), ("ctr", 6)):
        rows = ",\n  ".join("{" + ",".join(map(str, r)) + "}" for r in tabs[k])
        lines.append(f"static const unsigned char B_{k.upper()}[N_BASE][{n}] = {{\n  {rows}}};")
    out = Path(__file__).resolve().parents[2] / "csrc" / "moves.h"
    out.write_text("\n".join(lines) + "\n")
    print("wrote", out)


if __name__ == "__main__":
    main()
